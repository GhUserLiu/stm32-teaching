void ssd1306_char(uint8_t x, uint8_t page, char c)
{
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *g = font6x8[c - 0x20];
    for (int i = 0; i < 6; i++)
        fb[page & 7][x + i] = g[i];   /* 越界由调用方保证 x ≤ 122 */
}

void ssd1306_string(uint8_t x, uint8_t page, const char *s)
{
    while (*s) {
        ssd1306_char(x, page, *s++);
        x += 6;
        if (x > 122) break;
    }
}

void ssd1306_uint(uint8_t x, uint8_t page, uint32_t v)
{
    char buf[11];
    int i = 10;
    buf[i] = '\0';
    if (v == 0) { ssd1306_char(x, page, '0'); return; }
    while (v && i > 0) { buf[--i] = (char)('0' + v % 10); v /= 10; }
    ssd1306_string(x, page, &buf[i]);
}
