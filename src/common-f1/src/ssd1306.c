/**
 * @file    ssd1306.c
 * @brief   SSD1306 OLED 驱动：软件 I2C + 128x64 帧缓冲 + 6x8 字库
 */
#include "ssd1306.h"
#include "board_f1.h"
#include "f1_delay.h"

/* ---------------- 软件 I2C ---------------- */
#define SCL_H() gpio_set(OLED_SCL_PORT, OLED_SCL_PIN)
#define SCL_L() gpio_reset(OLED_SCL_PORT, OLED_SCL_PIN)
#define SDA_H() gpio_set(OLED_SDA_PORT, OLED_SDA_PIN)
#define SDA_L() gpio_reset(OLED_SDA_PORT, OLED_SDA_PIN)
#define SDA_READ() gpio_read(OLED_SDA_PORT, OLED_SDA_PIN)

static void i2c_pins_init(void)
{
    RCC->APB2ENR |= RCC_APB2ENR_IOPB;
    gpio_init(OLED_SCL_PORT, OLED_SCL_PIN, GPIO_MODE_OUT_OD_2);
    gpio_init(OLED_SDA_PORT, OLED_SDA_PIN, GPIO_MODE_OUT_OD_2);
    SCL_H(); SDA_H();
}

static void i2c_delay(void) { delay_us(4); }   /* ~100kHz */

static int i2c_start(void)
{
    SDA_H(); SCL_H(); i2c_delay();
    SDA_L(); i2c_delay();
    SCL_L(); i2c_delay();
    return 0;
}

static void i2c_stop(void)
{
    SDA_L(); i2c_delay();
    SCL_H(); i2c_delay();
    SDA_H(); i2c_delay();
}

/* 返回 ACK(0)/NACK(1) */
static int i2c_write_byte(uint8_t b)
{
    for (int i = 7; i >= 0; i--) {
        if ((b >> i) & 1) SDA_H(); else SDA_L();
        i2c_delay();
        SCL_H(); i2c_delay();
        SCL_L(); i2c_delay();
    }
    /* 读 ACK：释放 SDA，给第 9 个时钟 */
    SDA_H(); i2c_delay();
    SCL_H(); i2c_delay();
    int ack = SDA_READ();
    SCL_L(); i2c_delay();
    return ack;
}

/* ---------------- SSD1306 命令/数据 ---------------- */
#define SSD1306_ADDR   0x3C        /* 7 位地址（写操作 <<1 = 0x78） */

static void ssd1306_cmd(uint8_t cmd)
{
    i2c_start();
    i2c_write_byte(SSD1306_ADDR << 1);
    i2c_write_byte(0x00);          /* Co=0 D/C#=0：命令 */
    i2c_write_byte(cmd);
    i2c_stop();
}

static uint8_t fb[SSD1306_HEIGHT / 8][SSD1306_WIDTH];   /* 8 页 x 128 列 */

void ssd1306_init(void)
{
    i2c_pins_init();
    delay_ms(100);                 /* 上电稳定 */

    static const uint8_t init_seq[] = {
        0xAE,             /* 显示关 */
        0x20, 0x00,       /* 水平寻址模式 */
        0xB0,             /* 页起始地址 0 */
        0xC8,             /* COM 扫描方向：重映射 */
        0x00,             /* 列起始低地址 */
        0x10,             /* 列起始高地址 */
        0x40,             /* 显示起始行 0 */
        0x81, 0x7F,       /* 对比度 127 */
        0xA1,             /* 段重映射：列 127 接 SEG0 */
        0xA6,             /* 正常显示（非反色） */
        0xA8, 0x3F,       /* 多路复用 1/64 */
        0xA4,             /* 输出跟随 RAM 内容 */
        0xD3, 0x00,       /* 显示偏移 0 */
        0xD5, 0x80,       /* 时钟分频/振荡频率 */
        0xD9, 0xF1,       /* 预充电周期 */
        0xDA, 0x12,       /* COM 引脚硬件配置（128x64） */
        0xDB, 0x40,       /* VCOMH 电压 */
        0x8D, 0x14,       /* 电荷泵使能 */
        0xAF,             /* 显示开 */
    };
    for (unsigned i = 0; i < sizeof(init_seq); i++)
        ssd1306_cmd(init_seq[i]);
}

void ssd1306_fill(uint8_t val)
{
    for (int p = 0; p < 8; p++)
        for (int x = 0; x < SSD1306_WIDTH; x++)
            fb[p][x] = val;
}

void ssd1306_clear(void) { ssd1306_fill(0x00); }

void ssd1306_flush(void)
{
    for (int p = 0; p < 8; p++) {
        ssd1306_cmd(0xB0 | (uint8_t)p);   /* 页地址 */
        ssd1306_cmd(0x00);                /* 列低 */
        ssd1306_cmd(0x10);                /* 列高 */
        i2c_start();
        i2c_write_byte(SSD1306_ADDR << 1);
        i2c_write_byte(0x40);             /* 数据 */
        for (int x = 0; x < SSD1306_WIDTH; x++)
            i2c_write_byte(fb[p][x]);
        i2c_stop();
    }
}

